#!/usr/bin/env python
"""Generate reports/deliverables.md — the honest status of every deliverable.

Deliverable 16 of the project brief asks for "a clear summary of actual
achievements, limitations, and remaining blockers". This generates it from the
filesystem and the stored results, so a deliverable cannot be marked complete
unless the artefact it names actually exists.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.evaluation.aggregate import results_table, seed_summary  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def exists(rel: str) -> bool:
    p = ROOT / rel
    return p.exists() and (p.is_dir() or p.stat().st_size > 0)


def count(pattern: str) -> int:
    return len(list(ROOT.glob(pattern)))


def jload(rel: str):
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    L: list[str] = []
    A = L.append

    enc = jload("results/encryption_benchmarks/encrypted_inference.json")
    comp = jload("results/metrics/component_analysis.json")
    summ = seed_summary("main")

    A("# SAGE-HE — Deliverables, Achievements, Limitations and Blockers")
    A("")
    A("Research, Architecture & Implementation: **SUHAIB S Z**")
    A("")
    A("> Generated by `scripts/make_deliverables.py`. A deliverable is marked")
    A("> complete only if the artefact it names exists on disk.")
    A("")

    # ------------------------------------------------------- deliverables
    A("## 1. Deliverables")
    A("")
    items = [
        ("Working source code", "src", count("src/**/*.py") > 0,
         f"{count('src/**/*.py')} modules, {count('scripts/*.py')} runnable scripts"),
        ("Dataset, reproducibly obtainable", "scripts/download_dataset.py",
         exists("data/raw/manifest.json"),
         "fetched and verified against the published NEU-CLS specification"),
        ("Trained model checkpoints", "experiments/", count("experiments/*/*/best.pt") > 0,
         f"{count('experiments/*/*/best.pt')} checkpoints"),
        ("Baseline implementation", "src/models/baseline_jia.py",
         exists("src/models/baseline_jia.py"), "Jia et al. (2023), with assumptions documented"),
        ("Proposed architecture", "src/models/sage_he.py", exists("src/models/sage_he.py"),
         "dual branch, chunk attention, gated fusion, polynomial head"),
        ("CKKS encrypted inference", "src/encryption/", exists("src/encryption/ckks.py"),
         "genuine homomorphic evaluation, server holds no secret key"),
        ("Evaluation scripts", "src/evaluation/", exists("src/evaluation/metrics.py"),
         "metrics, aggregation, paired significance testing"),
        ("Experiment results and logs", "experiments/",
         count("experiments/*/*/result.json") > 0,
         f"{count('experiments/*/*/result.json')} completed runs with full history"),
        ("Performance comparison tables", "reports/technical_report.md",
         exists("reports/technical_report.md"), "generated from results, never hand-entered"),
        ("Architecture diagrams", "diagrams/", count("diagrams/*.svg") >= 12,
         f"{count('diagrams/*.svg')} diagrams (SVG + PNG), shapes verified against the code"),
        ("Grad-CAM visualisations", "results/gradcam/",
         exists("results/gradcam/gradcam_per_class.png"), "with explicit interpretive caveats"),
        ("Literature review and novelty assessment", "reports/literature_review.md",
         exists("reports/literature_review.md"), "15/15 citations machine-verified"),
        ("Technical report", "reports/technical_report.md",
         exists("reports/technical_report.md"), "generated end to end from results/"),
        ("Presentation (30+ slides)", "presentation/SAGE-HE.pptx",
         exists("presentation/SAGE-HE.pptx"), "rendered and layout-checked"),
        ("README with install and run commands", "README.md", exists("README.md"), ""),
        ("This summary", "reports/deliverables.md", True, ""),
    ]
    A("| # | Deliverable | Status | Artefact | Note |")
    A("|---|---|---|---|---|")
    for i, (name, path, ok, note) in enumerate(items, 1):
        A(f"| {i} | {name} | {'complete' if ok else '**INCOMPLETE**'} | `{path}` | {note} |")
    A("")

    # -------------------------------------------------------- achievements
    A("## 2. What was actually achieved")
    A("")
    if summ is not None and not summ.empty:
        def g(arch, col):
            r = summ[summ["arch"] == arch]
            return None if r.empty else float(r[col].iloc[0])
        sa, ja = g("sage_he", "test_accuracy_mean"), g("jia_baseline", "test_accuracy_mean")
        n = int(summ["test_accuracy_count"].max())
        if sa is not None and ja is not None:
            A(f"* **Trained and evaluated both models over {n} seeds** on one identical")
            A(f"  held-out split: SAGE-HE {sa*100:.2f}%, reproduced baseline {ja*100:.2f}%.")
    A("* **Reproduced and audited the base paper**, documenting eight under-specifications")
    A("  and the finding that its published 97.1% does not reproduce from its own description.")
    sens = results_table("sensitivity")
    if sens is not None and not sens.empty:
        best = float(sens["test_accuracy"].max())
        base_df = results_table("main")
        ours = None
        if base_df is not None and not base_df.empty:
            r = base_df[base_df["short"] == "jia_baseline_seed42"]
            ours = float(r["test_accuracy"].iloc[0]) if not r.empty else None
        top = max([v for v in (best, ours) if v is not None])
        A(f"  That finding was then **attacked rather than defended**: {len(sens)} further")
        A("  baselines vary the two things the paper leaves unspecified (convolution width")
        A("  and activation). ")
        if top * 100 >= 97.1:
            A(f"  One of them reaches the published figure ({top*100:.2f}%), so the correct")
            A("  conclusion is that the paper under-specifies its architecture rather than")
            A("  that its result does not reproduce.")
        else:
            A(f"  The best of them reaches {top*100:.2f}%, still short of 97.1%, so the gap is")
            A("  not explained by those assumptions.")
    A("* **Verified the dataset rather than trusting it**: conformance to the published")
    A("  NEU-CLS specification, exact-duplicate removal, and a near-duplicate leakage audit")
    A("  that showed the apparent leakage was an illumination artefact.")
    if enc:
        A(f"* **Genuine CKKS encrypted inference**: {enc['agreement_rate']*100:.2f}% agreement with")
        A(f"  plaintext over {enc['n_samples']} test images, with the error consuming only")
        A(f"  {enc.get('error_to_margin_ratio', float('nan'))*100:.2f}% of the tightest decision")
        A("  margin — a bound, not a coincidence of the sample.")
    A("* **An evaluation protocol that works on a saturated benchmark**, derived from the")
    A("  measured learning curve rather than guessed.")
    A("* **A complete, reproducible pipeline**: one command regenerates every number,")
    A("  figure, diagram, report section and slide.")
    A("")

    # --------------------------------------------------- negative results
    A("## 3. What did not work (reported, not buried)")
    A("")
    if comp:
        A(f"* **{comp['headline']['statement']}**")
        A("")
        con = comp.get("ablation_contrasts", {})
        for label, key in [
            ("adding the local branch", "local_branch_value (dual_gated − global_only)"),
            ("adding chunk attention", "chunk_attention_value (7 − 6)"),
            ("adding the Sobel prior", "sobel_prior_value (7 − 8)"),
            ("full model vs its own backbone", "full_vs_backbone (7 − 2)"),
        ]:
            v = con.get(key)
            if v and v["mean_delta"] is not None:
                dv = v.get("mean_delta_excluding_collapsed") or v["mean_delta"]
                mark = ("consistent on every seed" if v.get("all_same_sign")
                        else "**not** sign-consistent — not claimed")
                A(f"  * {label}: {dv*100:+.2f} points macro F1 ({mark})")
        lam = comp.get("sobel_lambda") or {}
        if lam.get("max_abs_drift_from_init") is not None:
            A(f"* **λ never learned.** It moves at most {lam['max_abs_drift_from_init']:.4f} from")
            A("  its initialisation, so it cannot serve as the readout it was designed to be.")
    A("* **Training collapses** in some very-low-data configurations; collapsed runs are")
    A("  flagged and excluded from robust statistics rather than silently averaged in.")

    dsg = results_table("design")
    abl = results_table("abl")
    if dsg is not None and not dsg.empty and abl is not None and not abl.empty:
        from src.viz.charts import aggregate_ablation
        gr = aggregate_ablation(
            abl[abl["short"].str.startswith("7_chunk_attention_seed")], "test_macro_f1")
        if not gr.empty:
            ref = float(gr["mean"].iloc[0])
            beats = []
            for prefix in ("res_", "contrast_", "compress_", "topk_"):
                sub = dsg[dsg["short"].str.startswith(prefix)]
                if sub.empty:
                    continue
                g = aggregate_ablation(sub, "test_macro_f1")
                for _, r in g.iterrows():
                    if r["mean"] > ref:
                        beats.append((r["stage"].replace("_", " "),
                                      (r["mean"] - ref) * 100))
            if beats:
                A("* **The design choices are mostly indistinguishable, not wrong.** Several")
                A(f"  variants have a higher mean than the specified configuration")
                A(f"  ({ref*100:.2f}% macro F1), but seed-to-seed spread at 61 training images is")
                A("  several points and swallows almost every gap. They are reported as")
                A("  indistinguishable rather than ranked — see the technical report, §6.5.")
    A("")
    A("The architectural claim is withdrawn. Two contrasts hold on every seed and carry")
    A("that conclusion — adding the local branch costs accuracy, and the full model scores")
    A("below its own backbone. The finer attributions (chunk attention vs. Sobel prior")
    A("taken separately) do not separate cleanly at three seeds and 61 training images,")
    A("and are not claimed.")
    A("")
    A("What the evidence supports is EfficientNet-B0 plus compression plus the CKKS head —")
    A("the privacy architecture without the extra feature machinery.")
    A("")

    # -------------------------------------------------------- limitations
    A("## 4. Limitations")
    A("")
    for line in [
        "**Single dataset.** NEU-CLS only; no cross-dataset validation.",
        "**Saturated benchmark.** Component conclusions come from a reduced-data regime and "
        "should not be extrapolated to full-data behaviour.",
        "**Small test set.** 360 images; one image is 0.28 accuracy points.",
        "**No GPU.** All training and all latencies are CPU measurements on 4 vCPU.",
        "**The privacy model is weaker than the base paper's goal.** The client holds the "
        "feature extractor; only the server side of the boundary is protected.",
        "**The baseline is a reconstruction**, not the authors' code.",
        "**No circuit privacy.** Noise flooding is not implemented.",
    ]:
        A(f"* {line}")
    A("")

    # ----------------------------------------------------------- blockers
    A("## 5. Remaining blockers")
    A("")
    A("* **No GPU was available in this environment.** The brief specifies GPU training;")
    A("  everything was trained on CPU instead. The code selects CUDA automatically where")
    A("  present and needs no change on a GPU host.")
    A("* **`Privacy_concern.pdf` was referenced by the brief but never supplied.** The base")
    A("  paper is open access (CC BY 4.0), so it was retrieved from the publisher directly,")
    A("  including its tables — no analysis depends on the missing attachment.")
    A("* **Kaggle credentials were not available**, so NEU-CLS was obtained from a public")
    A("  mirror and verified against the published specification instead of trusted.")
    A("")

    out = ROOT / "reports" / "deliverables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))
    n_inc = sum(1 for _, _, ok, _ in items if not ok)
    print(f"written: {out} ({len(items)-n_inc}/{len(items)} deliverables complete)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
