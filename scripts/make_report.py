def pct(x, nd=2):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "—"
    return f"{x*100:.{nd}f}%"


def md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)



def _renumber(lines: list[str]) -> list[str]:
    """Renumber `## N. Title` sequentially and remap `### N.M` to match."""
    mapping: dict[str, str] = {}
    nxt = 1
    for ln in lines:
        m = re.match(r"^## (\d+)\. ", ln)
        if m:
            mapping[m.group(1)] = str(nxt)
            nxt += 1
    out = []
    for ln in lines:
        m = re.match(r"^## (\d+)\. (.*)$", ln)
        if m:
            out.append(f"## {mapping[m.group(1)]}. {m.group(2)}")
            continue
        m = re.match(r"^### (\d+)\.(\d+) (.*)$", ln)
        if m and m.group(1) in mapping:
            out.append(f"### {mapping[m.group(1)]}.{m.group(2)} {m.group(3)}")
            continue
        out.append(ln)
    return out


